export const getServiceBySlug = (slug) => {
  return servicesData.find((s) => s.slug === slug);
};

export const getRelatedServices = (serviceId) => {
  const current = servicesData.find((s) => s.id === serviceId);
  if (!current || !current.relatedServices) return [];
  return current.relatedServices
    .map((relId) => servicesData.find((s) => s.id === relId))
    .filter(Boolean);
};
